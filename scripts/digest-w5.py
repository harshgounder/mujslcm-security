#!/usr/bin/env python3
"""Digest wave 5 into research/DIGEST-W5.md plus a machine copy of every parsed row.

Deterministic: no model calls. Reads the 25 saved reports, extracts each one's tool rows
(name | url | what it does | access | driven by | machine-readable output | status), its
NO-TOOL GAPS, its BUILD CANDIDATES, and the opening lines of its VERDICT.
"""
import glob, json, os, re

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(BASE, "research")
OUT_MD = os.path.join(RES, "DIGEST-W5.md")
OUT_JSON = os.path.join(RES, "w5-rows.json")


def rows(text, require_url=True):
    """Markdown table rows returned as dicts. require_url=False accepts the no-tool-gap tables,
    which deliberately name no citable URL."""
    out = []
    head = None
    for line in text.split("\n"):
        if not line.strip().startswith("|"):
            head = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        if set(cells[0]) <= set("-: ") and cells[0]:
            continue
        if cells[0].lower() in ("name", "rank", "asset", "id"):
            head = cells
            continue
        joined = " | ".join(cells)
        if require_url and not re.search(r"https?://", joined):
            continue
        if not require_url and (not cells[0] or cells[0].startswith("---")):
            continue
        out.append({"name": cells[0][:120], "cells": [c[:220] for c in cells[1:6]],
                    "head": head[:7] if head else None})
    return out


def section(text, wanted):
    lines = text.split("\n")
    out, on = [], False
    for l in lines:
        if l.startswith("#"):
            if on:
                break
            h = l.strip().lstrip("#").strip().lower()
            h = re.sub(r"^\d+[\).]\s*", "", h)
            on = h.startswith(wanted.lower())
            if on:
                out.append(l)
                continue
        if on:
            out.append(l)
    return "\n".join(out).strip()


def main():
    files = sorted(glob.glob(os.path.join(RES, "w5-*.md")))
    machine = {}
    md = ["# DIGEST-W5: the gap register turned into 25 reports", ""]
    md.append(f"Source: {len(files)} saved wave-5 reports under `research/`, "
              f"{sum(os.path.getsize(f) for f in files):,} chars total. "
              "Generated by `scripts/digest-w5.py`, deterministic parse, no model calls.")
    md.append("")
    md.append("| brief | chars | tool rows | no-tool gaps | build candidates |")
    md.append("|---|---:|---:|---:|---:|")
    per = []
    for f in files:
        t = open(f, encoding="utf-8", errors="replace").read()
        name = os.path.basename(f)[:-3]
        r = rows(t)
        ntg = rows(section(t, "NO-TOOL GAPS"), require_url=False)
        bcs = rows(section(t, "BUILD CANDIDATES"), require_url=False)
        ver = section(t, "VERDICT") or section(t, "Executive Summary")
        vline = ""
        for l in ver.split("\n"):
            if l.strip() and not l.startswith("#"):
                vline = l.strip()[:300]
                break
        per.append((name, r, ntg, bcs, vline))
        machine[name] = {"rows": r, "no_tool_gaps": ntg, "build_candidates": bcs, "verdict": vline,
                         "chars": len(t)}
        md.append(f"| {name} | {len(t):,} | {len(r)} | {len(ntg)} | {len(bcs)} |")
    md.append("")
    md.append(f"Totals: {sum(len(p[1]) for p in per)} tool rows, "
              f"{sum(len(p[2]) for p in per)} no-tool gap rows, "
              f"{sum(len(p[3]) for p in per)} build candidate rows.")
    md.append("")
    for name, r, ntg, bcs, vline in per:
        md.append(f"## {name}")
        md.append("")
        if vline:
            md.append(f"- verdict head: {vline}")
        md.append(f"- tool rows: {len(r)}, no-tool gaps: {len(ntg)}, build candidates: {len(bcs)}")
        for row in r[:12]:
            md.append(f"  - {row['name']} | {' | '.join(row['cells'][:3])[:240]}")
        if ntg:
            md.append("- no-tool gaps named:")
            for row in ntg[:8]:
                md.append(f"  - {row['name']} | {row['cells'][0][:200]}")
        if bcs:
            md.append("- build candidates named:")
            for row in bcs[:8]:
                md.append(f"  - {row['name']} | {row['cells'][0][:200]}")
        md.append("")
    open(OUT_MD, "w").write("\n".join(md))
    json.dump(machine, open(OUT_JSON, "w"), indent=1)
    print(f"wrote {OUT_MD} ({os.path.getsize(OUT_MD):,} bytes)")
    print(f"wrote {OUT_JSON} ({os.path.getsize(OUT_JSON):,} bytes)")
    print(f"tool rows {sum(len(p[1]) for p in per)} | no-tool gaps {sum(len(p[2]) for p in per)} "
          f"| build candidates {sum(len(p[3]) for p in per)}")


if __name__ == "__main__":
    main()
