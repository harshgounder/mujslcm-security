#!/usr/bin/env python3
"""Regenerate INDEX.md: a complete, honest file inventory of this repo.

Deterministic. Lists every tracked file by directory with its size, plus a header that states what
was counted and how. Re-run after any wave lands; do not hand-edit INDEX.md.
"""
import os, subprocess

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(BASE)

SKIP_DIRS = {".git", "__pycache__", ".venv"}
NOTES = {
    "briefs/": "one self-contained prompt per research run. w1 to w3 are the campaign fleet, "
               "w5-g-01 to w5-g-25 are the gap-register briefs.",
    "ledger/": "one json per run: name, run_id, processor, key tail, launch time, done flag, "
               "state and char count after landing. Tails only, never full keys.",
    "research/": "the reports themselves, verbatim, one file per run, plus the syntheses and the "
                 "wave digests. Digests are deterministic parses, not model output.",
    "recon/": "raw hands-on captures: headers, bodies, certificates, DNS, certificate transparency, "
              "the probe outputs, and the round 1 to 3 layer evidence under recon/layers-2026-09-13.",
    "findings/": "the written analysis: findings F1 to F10, the reaudit, the attack-surface map, the "
                 "test plan, the aggressive playbook, the OSINT review, and the LAYER-MAP.",
    "scripts/": "the pipeline: brief generators, wave launchers, watchers, probes, the reaudit, the "
                "digest generator, the index generator, and the gated auth-phase suite.",
    "disclosures/": "the disclosure letter template that unlocks the authorized phase.",
}


def tracked_files():
    out = subprocess.run(["git", "ls-files"], capture_output=True, text=True).stdout.split()
    extra = []
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            p = os.path.relpath(os.path.join(root, f), ".")
            if p not in out and not p.endswith(".pyc"):
                extra.append(p)
    return sorted(set(out) | set(extra))


def human(n):
    for unit in ("B", "K", "M"):
        if n < 1024:
            return f"{n:.1f}{unit}" if unit != "B" else f"{n}B"
        n /= 1024
    return f"{n:.1f}G"


def main():
    files = tracked_files()
    by_dir = {}
    for p in files:
        d = os.path.dirname(p) + "/" if os.path.dirname(p) else "root/"
        by_dir.setdefault(d, []).append(p)
    total_bytes = sum(os.path.getsize(p) for p in files if os.path.exists(p))
    lines = ["# INDEX.md: complete file inventory", ""]
    lines.append(f"Generated by `scripts/make-index.py`, deterministic, no model calls.")
    lines.append(f"Tracked files: **{len(files)}**. Total bytes on disk: **{total_bytes:,}** "
                 f"({human(total_bytes)}).")
    lines.append("")
    lines.append("Counted from `git ls-files` plus any present file not yet tracked, so an "
                 "uncommitted report still shows here. Sizes are on-disk bytes.")
    lines.append("")
    for d in sorted(by_dir, key=lambda x: (x != "root/", x)):
        entries = by_dir[d]
        size = sum(os.path.getsize(p) for p in entries if os.path.exists(p))
        lines.append(f"## {d} ({len(entries)} files, {human(size)})")
        lines.append("")
        if d in NOTES:
            lines.append(NOTES[d])
            lines.append("")
        for p in sorted(entries):
            lines.append(f"- `{p}`  ({human(os.path.getsize(p)) if os.path.exists(p) else 'missing'})")
        lines.append("")
    open("INDEX.md", "w").write("\n".join(lines))
    print(f"INDEX.md written: {len(files)} files, {total_bytes:,} bytes")


if __name__ == "__main__":
    main()
